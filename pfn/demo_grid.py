"""那 12 个 ell 意味着什么：它就是先验，是模型全部的世界观。"""

import numpy as np

from exp_why_axis import PRIORS, log_marginal, sample_gp

np.set_printoptions(precision=3, suppress=True, linewidth=110)

ELLS, NOISES = PRIORS["A(只有尺度变)"]
NOISE = 0.1


def bar(w, width=46):
    return "█" * int(round(w * width))


def posterior_weights(xc, yc):
    lml = np.array([log_marginal(xc, yc, e, NOISE) for e in ELLS])
    w = np.exp(lml - lml.max())
    return w / w.sum()


print(f"""
==============================================================================
1. 这 12 个数就是先验 P，不是超参数
==============================================================================

  ELL_GRID = np.exp(np.linspace(np.log(0.3), np.log(3.0), 12))
           = {np.round(ELLS, 3)}

  「先验 P」的完整定义只有一句话：
      每生成一个任务，从这 12 个数里**等概率**抽一个当 ell，噪声固定 0.1。

  所以模型 A 的整个世界观就是：「世上的函数只有 12 种抖法。」
  它训练时见过的 72 万个任务，无一例外都来自这 12 种之一。
""")

print("  等距吗？看相邻两项的比值：")
ratios = ELLS[1:] / ELLS[:-1]
print(f"    {np.round(ratios, 4)}")
print(f"""
  比值全是 {ratios[0]:.4f}——**是等比不是等差**。因为 ell 是尺度参数，
  有意义的是「大几倍」而不是「大多少」。0.3→0.37 和 2.43→3.0 在感知上是同一步。
  所以用 log 空间均匀铺点，这是正数尺度参数的标准做法。
""")

print("""==============================================================================
2. 先验 = 均匀，后验 = 数据把权重重新分配
==============================================================================
""")
print("  没看到任何数据时，12 个候选的权重是均匀的（每个 1/12 = 0.083）：\n")
for e in ELLS:
    print(f"    ell={e:>5.3f}  {1/12:.3f}  {bar(1/12)}")

rng = np.random.default_rng(0)
for ell_true, label in [(0.854, "在先验支撑内"), (0.370, "在先验支撑内")]:
    x = np.sort(rng.uniform(-3, 3, 25))
    y = sample_gp(rng, x, ell_true) + NOISE * rng.standard_normal(25)
    w = posterior_weights(x, y)
    est = float(np.exp(w @ np.log(ELLS)))
    print(f"\n  看到 25 个点、真实 ell={ell_true}（{label}）之后：\n")
    for e, wi in zip(ELLS, w):
        mark = "  <- 真值最近" if abs(e - ell_true) < 1e-6 else ""
        print(f"    ell={e:>5.3f}  {wi:.3f}  {bar(wi)}{mark}")
    print(f"    后验均值（几何）ell ≈ {est:.3f}")

print("""
  这就是「PFN 在做贝叶斯推断」的具体含义：它没有在拟合参数，
  而是在这 12 个候选上重新分配信念，然后按信念加权做预测。
""")

print("""==============================================================================
3. 边界很关键：先验支撑之外发生什么
==============================================================================
""")
for ell_true in [8.0, 0.08]:
    x = np.sort(rng.uniform(-3, 3, 25))
    y = sample_gp(rng, x, ell_true) + NOISE * rng.standard_normal(25)
    w = posterior_weights(x, y)
    est = float(np.exp(w @ np.log(ELLS)))
    side = "比最平缓的候选还平缓" if ell_true > ELLS[-1] else "比最抖的候选还抖"
    print(f"  真实 ell={ell_true}（{side}，**在 [0.3, 3.0] 之外**）：\n")
    for e, wi in zip(ELLS, w):
        print(f"    ell={e:>5.3f}  {wi:.3f}  {bar(wi)}")
    print(f"    后验均值 ell ≈ {est:.3f}  —— 权重全堆在网格{'上' if ell_true > 3 else '下'}边界\n")

print(f"""  模型没有「我不知道」这个选项。数据再怎么不像它见过的东西，
  它也只能在这 12 个候选里挑一个最接近的，然后**照常自信地给出预测**。
  这就是「先验错配」的机械原理，也是整篇论文的出发点。

  代码里对网格宽度有一句注释，正是在说这件事：
      # 范围要够宽，否则似然会顶在网格边界上，anchor 就没有掰动的余地
  如果网格太窄，正常数据就已经把权重顶到边界了，再加 anchor 也推不动，
  掰动实验会假阴性。

==============================================================================
4. 为什么偏偏是 12
==============================================================================

  不是精心调出来的最优值，是被两头夹出来的：

  下限：候选太少 -> 权重容易顶到边界 -> 没有掰动余地（见上一节）
  上限：候选太多 -> 同样步数下每种见得少 -> 训练不足

  而且后来的 A144 实验证明 **12 不是甜点**：把单隐变量模型的候选从 12 铺到 144，
  跟随精确贝叶斯的相关系数反而从 +0.863 升到 +0.924。所以「候选多」本身不是坏事。

  12 真正的来源是**为了和模型 C 对齐**：C 要同时变尺度和噪声，取 12×12=144 种组合，
  于是 A 和 B 各取 12 保持单轴的量级可比。而这个设计一度制造了混淆——
  C 跟得差，到底是因为「组合多」还是「两个隐变量纠缠」？A144 实验就是为了拆开这一点：
  组合数同为 144、步数相同，单隐变量的 A144 仍然远好于双隐变量的 C，
  所以差距来自纠缠，不是组合数。

==============================================================================
5. 和真实表格 PFN 的关系
==============================================================================

  这 12 个数是个**玩具替身**。真实的 TabICL / TabPFN 先验是一个结构因果模型生成器，
  隐变量有几十上百个（图结构、激活函数、噪声、特征变换……），而且互相纠缠。

  用 12 个数的玩具版，是因为它保留了唯一重要的性质——**有一个必须逐任务推断的隐变量**
  ——同时换来一个真实 PFN 给不了的东西：**正确答案可以精确算出来**。
  只有能算出「P 下的贝叶斯后验到底该是多少」，才能判断 PFN 是「算错了」还是「先验错了」。
""")
